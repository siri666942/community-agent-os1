def banlist_block() -> str:
    """从质检词表动态生成硬性红线清单,注入生成提示词,提升一次通过率。"""
    rules = kb.qc_rules()
    lines = ["硬性红线(输出前逐条自查,命中任何一条即违规,会被合规打回):"]
    for item in rules.get("sensitive_replacements", []):
        lines.append(f"- 禁用「{item['word']}」→ 改用「{item['replacement']}」")
    for w in rules.get("banned_absolute", []):
        lines.append(f"- 禁用绝对化表述「{w}」")
    for w in rules.get("banned_overpromise", []):
        lines.append(f"- 禁用过度承诺「{w}」")
    return "\n".join(lines)
